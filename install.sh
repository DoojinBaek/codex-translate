#!/bin/bash
# Registers the Codex Translate native messaging host with Chromium browsers
# (Aside, Chrome, ...). The browser starts the host itself when the extension
# needs it, so there is no server to keep running.
set -euo pipefail
NAME="com.codex_translate.bridge"
EXT_ID="mjfjdablbdhcbjabnpnpmhapgacfcfeg"   # fixed by the "key" in extension/manifest.json
SRC="$(cd "$(dirname "$0")" && pwd)/bridge"
DEST="$HOME/Library/Application Support/codex-translate"
VERSION="$(sed -n 's/.*VERSION = "\([^"]*\)".*/\1/p' "$SRC/version.mjs" | head -1)"

# Keep the symlink paths (e.g. /opt/homebrew/bin/node): they survive upgrades,
# while the resolved Cellar paths do not.
# A keg-only formula (node@22) can put .../Cellar/<formula>/<version>/bin on PATH
# directly; use Homebrew's version-free opt/ link to the same file instead.
stable() {
  local p="$1"
  if [[ "$p" =~ ^(.*)/Cellar/([^/]+)/[^/]+/(.*)$ ]]; then
    local o="${BASH_REMATCH[1]}/opt/${BASH_REMATCH[2]}/${BASH_REMATCH[3]}"
    [ -x "$o" ] && { echo "$o"; return; }
  fi
  echo "$p"
}
NODE="$(command -v node || true)"
CODEX="$(command -v codex || true)"
[ -z "$NODE" ] || NODE="$(stable "$NODE")"
[ -z "$CODEX" ] || CODEX="$(stable "$CODEX")"
[ -n "$NODE" ] || { echo "node를 찾을 수 없어요. Node.js 18 이상을 설치한 뒤 다시 실행하세요"; exit 1; }
"$NODE" -e 'process.exit(+process.versions.node.split(".")[0] >= 18 ? 0 : 1)' \
  || { echo "Node.js 18 이상이 필요해요 (현재 $("$NODE" --version))"; exit 1; }
if [ -n "$CODEX" ]; then
  echo "codex: $CODEX ($("$CODEX" --version 2>/dev/null || echo "버전 확인 실패"))"
  "$CODEX" login status >/dev/null 2>&1 || echo "⚠ codex 로그인이 필요해요: codex login"
else
  echo "⚠ codex를 찾을 수 없어요: npm i -g @openai/codex 후 codex login, 그리고 install.sh 를 다시 실행하세요"
fi
echo "node:  $NODE ($("$NODE" --version))"

mkdir -p "$DEST"
cp "$SRC"/*.mjs "$DEST/"   # state.json (learned Codex quirks) is left in place
# Keep a local copy of the extension too, so it keeps working when the source
# folder lives on iCloud Drive (files may be evicted) or an external drive.
rm -rf "$DEST/extension"
cp -R "$SRC/../extension" "$DEST/extension"

# Browsers launch hosts with a bare environment: pin paths and bake in the
# settings Codex needs from this shell.
BAKED=()
EXPORTS=""
for n in CODEX_HOME HTTPS_PROXY HTTP_PROXY ALL_PROXY NO_PROXY https_proxy http_proxy all_proxy no_proxy NODE_EXTRA_CA_CERTS SSL_CERT_FILE; do
  v="${!n-}"
  [ -n "$v" ] || continue
  EXPORTS+="export $n=$(printf '%q' "$v")"$'\n'
  BAKED+=("$n")
done

{
  echo '#!/bin/bash'
  echo '# Generated by install.sh. Never runs a login shell.'
  echo 'LOG="$HOME/Library/Logs/codex-translate.log"; mkdir -p "$HOME/Library/Logs"'
  echo "DEST=$(printf '%q' "$DEST")"
  echo "INSTALL_NODE=$(printf '%q' "$NODE")"
  echo "INSTALL_CODEX=$(printf '%q' "$CODEX")"
  printf '%s' "$EXPORTS"
  cat <<'SH'
pick() { for c in "$@"; do [ -n "$c" ] && [ -x "$c" ] && { echo "$c"; return 0; }; done; return 1; }
if sort -V </dev/null >/dev/null 2>&1; then SORTV="sort -V"; else SORTV="sort"; fi
NVM_NODE="$(ls -d "$HOME"/.nvm/versions/node/*/bin/node 2>/dev/null | $SORTV | tail -1)"
NODE="$(pick "$INSTALL_NODE" /opt/homebrew/bin/node /usr/local/bin/node "$HOME/.volta/bin/node" "$NVM_NODE" || true)"
CODEX="$(pick "$INSTALL_CODEX" /opt/homebrew/bin/codex /usr/local/bin/codex "$HOME/.local/bin/codex" "$HOME/.volta/bin/codex" "$HOME/.npm-global/bin/codex" "$HOME/.bun/bin/codex" "${NVM_NODE%/node}/codex" || true)"
# Native messaging frame: 4-byte little-endian length + JSON (ASCII here, so ${#j} is the byte length).
emit() { j="$1"; n=${#j}; printf "$(printf '\\%03o\\%03o\\%03o\\%03o' $((n&255)) $(((n>>8)&255)) $(((n>>16)&255)) $(((n>>24)&255)))"; printf '%s' "$j"; }
if [ -z "$NODE" ]; then
  echo "$(date -u +%FT%TZ) host.sh: node not found" >>"$LOG"
  emit '{"fatal":{"code":"node_missing","message":"","action":"","retryable":false}}'
  sleep 1; exit 1
fi
if [ -z "$CODEX" ]; then
  echo "$(date -u +%FT%TZ) host.sh: codex not found" >>"$LOG"
  emit '{"fatal":{"code":"codex_missing","message":"","action":"","retryable":false}}'
  sleep 1; exit 1
fi
export CODEX_BIN="$CODEX"
export PATH="$(dirname "$NODE"):$(dirname "$CODEX"):/opt/homebrew/bin:/usr/local/bin:$HOME/.local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
exec "$NODE" "$DEST/host.mjs" 2>>"$LOG"
SH
} > "$DEST/host.sh"
chmod +x "$DEST/host.sh"

MANIFEST=$(cat <<JSON
{
  "name": "$NAME",
  "description": "Codex Translate bridge",
  "path": "$DEST/host.sh",
  "type": "stdio",
  "allowed_origins": ["chrome-extension://$EXT_ID/"]
}
JSON
)

AS="$HOME/Library/Application Support"
registered=()
skipped=()
for dir in "Aside" "Google/Chrome" "Google/Chrome Beta" "Google/Chrome Canary" "Chromium" \
           "BraveSoftware/Brave-Browser" "Microsoft Edge" "Arc/User Data" "Vivaldi"; do
  if [ -d "$AS/$dir" ]; then
    mkdir -p "$AS/$dir/NativeMessagingHosts"
    echo "$MANIFEST" > "$AS/$dir/NativeMessagingHosts/$NAME.json"
    registered+=("$dir")
  else
    skipped+=("$dir")
  fi
done

echo
echo "Codex Translate $VERSION 설치 완료"
if [ ${#registered[@]} -gt 0 ]; then
  for d in "${registered[@]}"; do echo "  ✓ $d"; done
else
  echo "  지원하는 브라우저 프로필 폴더를 찾지 못했어요"
fi
[ ${#skipped[@]} -gt 0 ] && echo "  (설치 안 됨: $(IFS=,; echo "${skipped[*]}" | sed 's/,/, /g'))"
if [ ${#BAKED[@]} -gt 0 ]; then echo "host.sh에 넣은 환경 변수: ${BAKED[*]}"; fi
echo "host: $DEST/host.sh"
echo "log:  ~/Library/Logs/codex-translate.log"
echo
echo "확장 폴더 (chrome://extensions → 압축해제된 확장 프로그램 로드에서 선택):"
echo "  $DEST/extension"
echo "  Finder에서 Cmd+Shift+G 로 위 경로를 붙여넣으면 됩니다."
echo "확장을 업데이트했다면 브라우저의 확장 관리 페이지에서 새로고침(↻) 하세요"
